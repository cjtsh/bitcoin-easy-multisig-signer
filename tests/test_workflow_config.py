class SweepFailClosedPins(unittest.TestCase):
    """The sweep must never turn a failure to read into "ok".

    That is exactly what happened on the Windows job: `git show ref:path
    2>/dev/null || true` returned nothing, both body checks found nothing to
    match, and a branch that publishes was reported clean. Four behavioural
    tests went red there and stayed green on Mac and Linux. These pins hold the
    half the behaviour cannot easily reach: an unreadable body is an offender,
    and no external matcher is involved whose absence could go silent.
    """

    @classmethod
    def setUpClass(cls):
        cls.text = (ROOT / "scripts" / "check-publish-paths.sh").read_text(
            encoding="utf-8")

    def test_an_unreadable_workflow_body_is_an_offender(self):
        self.assertIn("unreadable-workflow", self.text,
                      "a body the sweep cannot read must be reported, not passed")
        self.assertIn('report "$branch" "$path" "unreadable-workflow"', self.text)

    def test_the_body_read_is_not_allowed_to_swallow_its_failure(self):
        reads = [line for line in self.text.splitlines()
                 if "cat-file blob" in line and "body=" in line]
        self.assertTrue(reads, "the sweep must read each workflow body with git cat-file")
        for line in reads:
            self.assertNotIn("|| true", line,
                             "the body read must fail loudly: " + line)
            self.assertIn("if !", line,
                          "the body read must be gated on its own success: " + line)

    def test_the_sweep_matches_bodies_with_bash_and_not_with_grep(self):
        """grep is an external tool. When it is missing or broken, a pipeline
        that ends in grep silently reports "no match" — a refusal becomes a
        pass. Bash's own [[ ]] cannot do that."""
        code = "\n".join(line for line in self.text.splitlines()
                         if not line.lstrip().startswith("#"))
        self.assertNotRegex(code, r"(^|[\s|;&])grep(\s|$)",
                            "the sweep must not depend on grep to decide a refusal")
        self.assertIn("nocasematch", self.text)
        self.assertIn("CONTENT_WRITE_RE", self.text)

    def test_the_bodies_come_from_object_ids_not_from_rev_colon_path(self):
        """`git show ref:path` is the read that went blind on Windows.

        An object id from ls-tree has no path syntax for anything to mangle.

        CT-103: the first version of this pin searched the whole file for
        `git cat-file blob`, and the header comment at the top of the script
        carries that phrase — so the pin stayed green for a regression that
        rewrote the read to `git show ref:path`. It now asserts the executable
        line, with the comment lines removed first.
        """
        code = "\n".join(line for line in self.text.splitlines()
                         if not line.lstrip().startswith("#"))
        self.assertIn('if ! body="$(git cat-file blob "$oid"', code,
                      "the body read must be the executable git cat-file line, "
                      "not a phrase a comment can carry")
        self.assertIn("git ls-tree -r", code)
        self.assertNotIn('git show "${ref}:${path}"', code)


class GuardBodyPins(unittest.TestCase):
    """CT-52: a guard is only a guard if its body can fail.

    The old pins asserted the step NAMES existed. A step named "Refuse an
    unsigned public release" whose body is `true` passes every one of them.
    These assert the refusal itself is in the body.
    """

    @classmethod
    def setUpClass(cls):
        cls.text = ACTIVE.read_text(encoding="utf-8")

    def _step_body(self, name: str) -> str:
        """The `run:` body of the step named `name`, and nothing else.

        A step ends at the next `- name:` (or at the next job key). The first
        version of this reached past the step into its neighbour, so deleting
        one guard's `exit 1` still left one in the captured text and the pin
        stayed green — the exact shape of a test that cannot fail.
        """
        lines = self.text.splitlines()
        marker = f"- name: {name}"
        start = None
        indent = None
        for index, line in enumerate(lines):
            if line.strip() == marker:
                start = index
                indent = len(line) - len(line.lstrip())
                break
        self.assertIsNotNone(start, f"no step named {name!r} in {ACTIVE}")

        body = []
        for line in lines[start + 1:]:
            stripped = line.strip()
            current_indent = len(line) - len(line.lstrip())
            if stripped.startswith("- name:") and current_indent <= indent:
                break
            if stripped and not line.startswith(" " * (indent + 1)):
                # Outdented to the step's own level or above: the step is over.
                if not stripped.startswith("- name:"):
                    break
            body.append(line)
        text = "\n".join(body)
        self.assertIn("run:", text,
                      f"{name} has no run: block; nothing for it to refuse with")
        return text

    def test_the_publish_sweep_gate_step_fails_closed_in_its_body(self):
        body = self._step_body("Refuse a second publish path on any ref")
        self.assertIn("scripts/check-publish-paths.sh", body)
        self.assertIn("exit 1", body,
                      "the gate must exit 1 itself when the sweep fails")
        self.assertIn(">&2", body, "the refusal must go to stderr")

    def test_every_named_guard_step_contains_its_own_refusal(self):
        for name, refusal in (
            ("Refuse an unsigned public release",
             "Publishing requires a signed and notarized build."),
            ("Require the default branch for publication",
             "Public releases must be dispatched from main."),
            ("Refuse a second publish path on any ref",
             "A non-main ref can publish."),
        ):
            body = self._step_body(name)
            self.assertIn("exit 1", body,
                          f"{name} must be able to fail; its body has no exit 1")
            self.assertIn(refusal, body,
                          f"{name} must name what it refused")
            self.assertIn(">&2", body,
                          f"{name} must send the refusal to stderr")


class PublishGuardBranchPins(unittest.TestCase):
    """CT-77…CT-81: four publish-path exits share a step body, so a step pin is blind to one of them.

    CT-52 pinned whole step bodies. CT-81 is that pin's blind spot: the candidate
    refusal, the unsigned/unnotarized refusal, the tag-exists refusal and the
    tag-state-unclear refusal live inside ordinary `if` branches, and the GPG
    fail-closed refusal sits inside a step three others never touch. Deleting one
    `exit` leaves the other refusals in the captured text, so the step-level pin
    stayed green — a guard nobody could watch fail.

    These slice each guard from the line that prints its own refusal to the `fi`
    that closes that branch, and require the exit to be the last thing the branch
    does. A later statement is exactly what absorbs a failure.
    """

    # (a line only this guard prints, the exit it must reach, the finding it closes)
    GUARDS = (
        ("Candidate build: v${VERSION} was built and NOT published.",
         "exit 0", "CT-77"),
        ("GPG_PRIVATE_KEY is not set; a release cannot ship an unsigned",
         "exit 1", "CT-79"),
        ("The tag $tag already exists.", "exit 1", "CT-78"),
        ("Could not verify remote tag state; refusing publication.",
         "exit 1", "CT-80"),
    )

    @classmethod
    def setUpClass(cls):
        cls.text = ACTIVE.read_text(encoding="utf-8")

    def _branch(self, anchor: str) -> list[str]:
        """The lines from the guard's own refusal through its closing `fi`."""
        lines = self.text.splitlines()
        start = next((index for index, line in enumerate(lines) if anchor in line), None)
        self.assertIsNotNone(start, f"no guard in {ACTIVE} prints {anchor!r}")
        for index in range(start, len(lines)):
            if lines[index].strip() == "fi":
                return lines[start:index + 1]
        self.fail(f"{anchor!r} is printed but never closed by a `fi`")

    @staticmethod
    def _statements(branch: list[str]) -> list[str]:
        """The branch's executable lines: no blanks, comments, or the closing `fi`."""
        return [line.strip() for line in branch
                if line.strip() and not line.strip().startswith("#")
                and line.strip() != "fi"]

    def test_every_publish_guard_ends_at_its_own_exit(self):
        for anchor, exit_line, finding in self.GUARDS:
            with self.subTest(finding=finding, guard=anchor):
                statements = self._statements(self._branch(anchor))
                self.assertIn(exit_line, statements,
                              f"{finding}: {anchor!r} does not refuse with {exit_line!r}")
                self.assertEqual(statements[-1], exit_line,
                                 f"{finding}: {anchor!r} does not end at {exit_line!r}; "
                                 "a statement after the exit absorbs the refusal")


@unittest.skipIf(yaml is None, "PyYAML not installed; workflow lint skipped")
class ReleaseCredentialScopePins(unittest.TestCase):
    """CT-97: a release credential must be environment-scoped, never ref-visible.

    A GitHub **repository** secret is handed to a job on any ref, so a dispatch
    at a historical tag runs that tag's own frozen workflow text but still
    receives today's signing keys — tags are immutable history and cannot be
    repaired, so the fix is platform-side: the credentials live in two protected
    environments whose deployment rule allows `main` only, and the jobs that use
    them declare those environments. These pins hold the repository half, so a
    later edit cannot quietly unscope a credential; the platform half is checked
    by `scripts/check-release-credentials.sh` (see ReleaseCredentialCheckTests in
    tests/test_release_credentials.py). Splitting the credential sets is also
    least privilege: the job that needs the release key never loads the Apple
    identity.
    """

    RELEASE_SECRETS = ("GPG_PRIVATE_KEY", "GPG_PASSPHRASE")
    APPLE_SECRETS = (
        "MAC_CERT_P12_BASE64",
        "MAC_CERT_PASSWORD",
        "MAC_APP_SPECIFIC_PASSWORD",
    )
    SCOPE = {"macos": "apple-signing", "checksums": "release-signing"}

    def setUp(self):
        self.text = ACTIVE.read_text(encoding="utf-8")
        self.jobs = yaml.safe_load(self.text)["jobs"]

    @property
    def credentials(self) -> tuple:
        return self.RELEASE_SECRETS + self.APPLE_SECRETS

    def _job_body(self, name: str) -> str:
        """The raw text of one top-level job, comments included.

        Sliced from the text rather than re-serialized: `yaml.safe_dump` would
        drop the comments that explain why each declaration exists.
        """
        pattern = re.compile(
            rf"^  {re.escape(name)}:\n(.*?)(?=^  [A-Za-z0-9_-]+:\n|\Z)", re.M | re.S
        )
        match = pattern.search(self.text)
        self.assertIsNotNone(match, f"{ACTIVE.name} has no job named {name}")
        return match.group(1)

    def _jobs_naming_a_credential(self) -> dict:
        found = {}
        for name in self.jobs:
            body = self._job_body(name)
            named = sorted(s for s in self.credentials if f"secrets.{s}" in body)
            if named:
                found[name] = (body, named)
        return found

    def test_every_job_that_names_a_credential_declares_an_environment(self):
        naming = self._jobs_naming_a_credential()
        self.assertTrue(naming, "no job names a release credential; the workflow changed shape")
        for name, (body, named) in naming.items():
            with self.subTest(job=name, secret=named[0]):
                self.assertIn(
                    "environment:",
                    body,
                    f"{name} names {named[0]} but declares no environment: a repository "
                    "secret reaches that job on every ref, including a historical tag",
                )

    def test_the_scope_map_is_exactly_the_documented_pair(self):
        found = {}
        for name, (body, named) in self._jobs_naming_a_credential().items():
            match = re.search(r"^    environment: (\S+)$", body, re.M)
            self.assertIsNotNone(match, f"{name} names {named[0]} but declares no environment")
            found[name] = match.group(1)
        self.assertEqual(
            found,
            self.SCOPE,
            "the credential scope map changed; move it deliberately and update SIGNING.md "
            "and scripts/check-release-credentials.sh together",
        )

    def test_no_other_workflow_file_names_a_release_credential(self):
        for path in all_workflows():
            if path.resolve() == ACTIVE.resolve():
                continue
            text = path.read_text(encoding="utf-8")
            for secret in self.credentials:
                self.assertNotIn(
                    f"secrets.{secret}",
                    text,
                    f"{path.name} names {secret}; a second workflow holding a release "
                    "credential is a second, unscoped path to it",
                )

    def test_the_release_key_is_reachable_only_on_the_publish_path(self):
        """The GPG step is already `if: inputs.publish`, so the release-signing
        environment is entered on a promotion and never by a candidate run."""
        steps = re.split(r"\n      - ", self._job_body("checksums"))
        naming = [step for step in steps if "secrets.GPG_" in step]
        self.assertEqual(len(naming), 1, "expected exactly one step in checksums to name the release key")
        self.assertIn("inputs.publish", naming[0],
                      "the release key must stay on the publish path")
        for secret in self.RELEASE_SECRETS:
            self.assertIn(f"secrets.{secret}", naming[0])

    def test_the_apple_credentials_stay_on_the_notarize_path(self):
        """An unsigned test build must keep working with no Apple credential and
        no environment gate, so those names may appear only in notarize-guarded
        steps."""
        steps = re.split(r"\n      - ", self._job_body("macos"))
        naming = [step for step in steps if "secrets.MAC_" in step]
        self.assertEqual(len(naming), 2, "expected exactly the two notarize steps to name Apple credentials")
        for step in naming:
            self.assertIn("inputs.notarize", step,
                          "an Apple credential must stay on the notarize path")

    def test_the_documents_name_the_control_and_its_check(self):
        signing = (ROOT / "SIGNING.md").read_text(encoding="utf-8")
        process = (ROOT / "RELEASE-PROCESS.md").read_text(encoding="utf-8")
        for environment in self.SCOPE.values():
            self.assertIn(environment, signing, f"SIGNING.md must name the {environment} environment")
        self.assertIn("scripts/check-release-credentials.sh", signing)
        self.assertIn("scripts/check-release-credentials.sh", process,
                      "RELEASE-PROCESS.md must name the standing check as a promotion step")


class ReleaseNotesTests(unittest.TestCase):
    """What a downloader reads must not describe the build as two different things.

    v0.4.12 was published saying it was "notarized by Apple" AND "Unsigned,
    unnotarized test build" on consecutive lines, because the template emitted a
    hardcoded unsigned line regardless of which mode had just been chosen. The
    release notes are the first thing anyone reads, and nobody re-reads them.

    Deliberately NOT gated on PyYAML: this renders the template with the shell that
    runs it in CI, so it needs nothing but bash.
    """

    @classmethod
    def setUpClass(cls):
        cls.text = ACTIVE.read_text(encoding="utf-8")

    def render(self, notarize: str) -> str:
        """Run the workflow's own notes block with one mode selected.

        The title is echoed alongside the notes so assertions can reach both.
        """
        # Keep the heredoc's own EOF terminator. Without it bash reads to the end of
        # input, so anything appended below - the title echo - becomes notes text.
        # The tag assignment is prepended because the split consumed it, and
        # release_title is built from it.
        body, _, _ = self.text.split('tag="v${VERSION}"', 1)[1].partition("          EOF")
        block = 'tag="v${VERSION}"\n' + body + "          EOF\n"
        script = block.replace("${{ inputs.notarize }}", notarize)
        # Print instead of writing notes.md, and drop the YAML indentation.
        script = script.replace("cat > notes.md <<EOF", "cat <<EOF")
        script = "\n".join(line[10:] if line.startswith(" " * 10) else line
                           for line in script.splitlines())
        runner = ("VERSION=9.9.9 GITHUB_REF_NAME=main GITHUB_SHA=abcdef1234567890\n"
                  + script + '\necho "TITLE=${release_title}"\n')
        # Never bash -c: Windows CreateProcess quoting mangles multiline -c
        # scripts into an exit-1/empty-stderr failure. run_bash_script writes
        # LF-terminated text to a file and executes that.
        result = run_bash_script(runner, cwd=ROOT, timeout=60)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout

    def title_of(self, notarize: str) -> str:
        for line in self.render(notarize).splitlines():
            if line.startswith("TITLE="):
                return line[len("TITLE="):]
        self.fail("the block did not set release_title")

    def test_the_title_is_the_version_and_nothing_else(self):
        """A release name is an identity, not a provenance record."""
        for mode in ("true", "false"):
            with self.subTest(notarize=mode):
                self.assertEqual(self.title_of(mode), "v9.9.9")

    def test_a_notarized_release_does_not_also_claim_to_be_unsigned(self):
        body = self.render("true")
        self.assertIn("notarized by Apple", body)
        self.assertNotIn("Unsigned", body)
        self.assertNotIn("unnotarized", body)

    def test_a_test_build_says_it_is_unsigned(self):
        body = self.render("false")
        self.assertIn("Unsigned", body)
        self.assertNotIn("notarized by Apple", body)

    def test_the_notes_offer_every_platform_and_its_verification(self):
        """One release page carries macOS, Windows, Linux and how to verify them."""
        body = self.render("true")
        self.assertIn("Bitcoin-Easy-Signer-v9.9.9-macOS.dmg", body)
        self.assertIn("Bitcoin-Easy-Signer-v9.9.9-windows-x64.zip", body)
        self.assertIn("Bitcoin-Easy-Signer-v9.9.9-linux-x86_64.AppImage", body)
        self.assertIn("bitcoin-easy-multisig-signer-v9.9.9.tar.gz", body)
        self.assertIn("SHA256SUMS.asc", body)
        self.assertIn("signing-key.asc", body)
        self.assertIn("Sigstore", body)
        self.assertIn("SIGNING.md", body)

    def test_the_notes_carry_no_stale_version_specific_boilerplate(self):
        """v0.4.12 shipped a paragraph about a Sparrow/Nunchuk change-path patch."""
        for mode in ("true", "false"):
            with self.subTest(notarize=mode):
                body = self.render(mode)
                self.assertNotIn("Sparrow", body)
                self.assertNotIn("Nunchuk", body)

    def test_the_heading_is_the_version_alone(self):
        """Build provenance is not a release name; it belongs in the notes body."""
        body = self.render("true")
        self.assertIn("## v9.9.9", body)
        self.assertNotIn("— Apple Silicon", body)
        self.assertNotIn("— notarized", body)
        self.assertNotIn("— unsigned", body)

    def test_the_notes_name_the_network_the_app_actually_opens_on(self):
        """The notes described the pre-0.6.0 opening screen.

        They said "Mutinynet is the opening network", which 0.6.1 makes false. The
        notes are generated by this workflow, so a release would have told every
        downloader to expect the opposite of what they get.
        """
        for mode in ("true", "false"):
            with self.subTest(notarize=mode):
                body = self.render(mode)
                self.assertNotIn("Mutinynet is the opening network", body)
                self.assertIn("Opens on Bitcoin mainnet", body)
                self.assertIn("Enter Developer Mode", body)
                self.assertIn("the app reopens on mainnet", body)


